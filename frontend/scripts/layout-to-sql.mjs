// Generates the V1 Flyway migration (WORKPLAN S0.5) from the library layout JSON,
// so the database and the seat map always describe the same library.
//
// Run from frontend/:
//   node scripts/layout-to-sql.mjs [path/to/layout.json]
// Default input: ../docs/layout/provisional-layout.json
// Output:        ../backend/src/main/resources/db/migration/V1__layout_and_students.sql
//
// V1 must never change once it is on main (Flyway checks it). When the on-site
// survey replaces the provisional layout, write a NEW migration that updates the
// seats instead of regenerating this one.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const input = resolve(process.argv[2] ?? resolve(here, '../../docs/layout/provisional-layout.json'))
const output = resolve(here, '../../backend/src/main/resources/db/migration/V1__layout_and_students.sql')

const layout = JSON.parse(readFileSync(input, 'utf8'))

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`)
const b = (v) => (v ? 'TRUE' : 'FALSE')

// SAMPLE students for demos and tests. First name and surname initial only, no
// photos, no real card numbers. Every row has is_sample = TRUE.
const SAMPLE_NAMES = [
  'Aarav S.', 'Ananya K.', 'Arjun M.', 'Diya P.', 'Ishaan R.', 'Kavya G.', 'Rohan B.', 'Meera T.',
  'Vihaan D.', 'Saanvi N.', 'Kabir J.', 'Aditi V.', 'Reyansh C.', 'Myra A.', 'Aryan L.', 'Tara H.',
  'Dhruv E.', 'Nisha F.', 'Kunal O.', 'Riya W.', 'Harsh Y.', 'Pooja Z.', 'Manav Q.', 'Sneha U.',
  'Yash I.', 'Simran K.', 'Nikhil S.', 'Isha M.', 'Arnav P.', 'Jasleen R.', 'Kartik G.', 'Avni B.',
  'Gurnoor T.', 'Prisha D.', 'Rahul N.', 'Navya J.', 'Siddharth V.', 'Tanvi C.', 'Parth A.', 'Zoya L.',
]

const lines = []
const out = (s = '') => lines.push(s)

out('-- V1: library layout and sample students (WORKPLAN S0.5).')
out('-- GENERATED by frontend/scripts/layout-to-sql.mjs from the layout JSON. Do not edit by hand.')
out('-- Never change this file once it is on main; Flyway checksums it. Later layout')
out('-- changes (for example after the on-site survey) go in a new migration.')
out('--')
out(`-- Layout source: ${layout.source ?? 'unknown'}`)
out(`-- Provisional: ${layout.provisional ? 'yes, seat counts are estimates until the survey' : 'no'}`)
out(`-- Bookable seats: ${layout.totalSeats}`)
out()

out(`CREATE TABLE floor (
    id           VARCHAR(4)   PRIMARY KEY,                -- GF, 1F, 2F, 3F
    number       SMALLINT     NOT NULL UNIQUE,            -- 0 for ground
    name         VARCHAR(40)  NOT NULL,
    short_name   VARCHAR(20)  NOT NULL,
    landmark     VARCHAR(120) NOT NULL,                   -- drawn under the seat map
    grid_width   SMALLINT     NOT NULL CHECK (grid_width > 0),
    grid_height  SMALLINT     NOT NULL CHECK (grid_height > 0),
    -- Opening hours are not known yet (survey, S0.4). NULL means "not set";
    -- the closing-time reset (S2.5) must handle that.
    open_time    TIME,
    close_time   TIME
);

-- A zone is one area of a floor: what the seat map draws as a section.
CREATE TABLE zone (
    id           VARCHAR(40)  PRIMARY KEY,                -- <floor>-<section>, e.g. 1F-tables
    floor_id     VARCHAR(4)   NOT NULL REFERENCES floor (id),
    section_code VARCHAR(30)  NOT NULL,
    name         VARCHAR(60)  NOT NULL,
    type         VARCHAR(12)  NOT NULL CHECK (type IN ('QUIET', 'GENERAL', 'DISCUSSION')),
    note         VARCHAR(200) NOT NULL,
    bookable     BOOLEAN      NOT NULL,                   -- FALSE: seminar hall, lounge, stacks
    from_row     SMALLINT     NOT NULL,
    to_row       SMALLINT     NOT NULL,
    sort_order   SMALLINT     NOT NULL,
    UNIQUE (floor_id, section_code),
    CHECK (to_row >= from_row)
);

CREATE TABLE seat (
    id             BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code           VARCHAR(16)  NOT NULL UNIQUE,          -- <floor>-<row><number>, e.g. 1F-C7
    floor_id       VARCHAR(4)   NOT NULL REFERENCES floor (id),
    zone_id        VARCHAR(40)  NOT NULL REFERENCES zone (id),
    row_label      VARCHAR(2)   NOT NULL,
    seat_number    SMALLINT     NOT NULL CHECK (seat_number > 0),
    table_id       VARCHAR(40),                           -- shared by seats at one table or room
    gx             SMALLINT     NOT NULL CHECK (gx >= 0),
    gy             SMALLINT     NOT NULL CHECK (gy >= 0),
    has_power      BOOLEAN      NOT NULL DEFAULT FALSE,
    near_window    BOOLEAN      NOT NULL DEFAULT FALSE,
    accessible     BOOLEAN      NOT NULL DEFAULT FALSE,
    out_of_service BOOLEAN      NOT NULL DEFAULT FALSE,
    version        BIGINT       NOT NULL DEFAULT 0,       -- optimistic locking (@Version)
    UNIQUE (floor_id, gx, gy),
    UNIQUE (floor_id, row_label, seat_number)
);

CREATE INDEX seat_zone_idx ON seat (zone_id);
CREATE INDEX seat_table_idx ON seat (table_id) WHERE table_id IS NOT NULL;

-- Furniture drawn on the map (tables, counters, rooms, non-bookable areas). Not clickable.
CREATE TABLE layout_fixture (
    id        BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    floor_id  VARCHAR(4)  NOT NULL REFERENCES floor (id),
    zone_id   VARCHAR(40) NOT NULL REFERENCES zone (id),
    kind      VARCHAR(10) NOT NULL CHECK (kind IN ('table', 'counter', 'room', 'area')),
    gx        SMALLINT    NOT NULL,
    gy        SMALLINT    NOT NULL,
    w         SMALLINT    NOT NULL CHECK (w > 0),
    h         SMALLINT    NOT NULL CHECK (h > 0),
    label     VARCHAR(60) NOT NULL
);

CREATE TABLE student (
    id         BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    card_id    VARCHAR(32) NOT NULL UNIQUE,               -- what the ID card barcode holds
    name       VARCHAR(80) NOT NULL,
    programme  VARCHAR(80),
    year       SMALLINT,
    is_sample  BOOLEAN     NOT NULL DEFAULT FALSE         -- TRUE for demo data, never real people
);`)
out()

out('-- Floors')
out('INSERT INTO floor (id, number, name, short_name, landmark, grid_width, grid_height) VALUES')
out(
  layout.floors
    .map((f) => `    (${q(f.id)}, ${f.number}, ${q(f.name)}, ${q(f.short)}, ${q(f.landmark)}, ${f.gridWidth}, ${f.gridHeight})`)
    .join(',\n') + ';',
)
out()

out('-- Zones (seat map sections)')
out('INSERT INTO zone (id, floor_id, section_code, name, type, note, bookable, from_row, to_row, sort_order) VALUES')
const zoneRows = []
for (const f of layout.floors) {
  f.sections.forEach((s, i) => {
    zoneRows.push(
      `    (${q(`${f.id}-${s.id}`)}, ${q(f.id)}, ${q(s.id)}, ${q(s.name)}, ${q(s.zone)}, ${q(s.note)}, ${b(s.bookable)}, ${s.fromRow}, ${s.toRow}, ${i + 1})`,
    )
  })
}
out(zoneRows.join(',\n') + ';')
out()

for (const f of layout.floors) {
  out(`-- Seats: ${f.name} (${f.seats.length})`)
  out('INSERT INTO seat (code, floor_id, zone_id, row_label, seat_number, table_id, gx, gy, has_power, near_window, accessible) VALUES')
  out(
    f.seats
      .map(
        (s) =>
          `    (${q(s.code)}, ${q(f.id)}, ${q(`${f.id}-${s.section}`)}, ${q(s.row)}, ${s.number}, ${q(s.tableId)}, ${s.gx}, ${s.gy}, ${b(s.power)}, ${b(s.window)}, ${b(s.accessible)})`,
      )
      .join(',\n') + ';',
  )
  out()
}

out('-- Fixtures (furniture drawn on the map)')
out('INSERT INTO layout_fixture (floor_id, zone_id, kind, gx, gy, w, h, label) VALUES')
const fixtureRows = []
for (const f of layout.floors) {
  for (const x of f.fixtures) {
    fixtureRows.push(`    (${q(f.id)}, ${q(`${f.id}-${x.section}`)}, ${q(x.kind)}, ${x.gx}, ${x.gy}, ${x.w}, ${x.h}, ${q(x.label)})`)
  }
}
out(fixtureRows.join(',\n') + ';')
out()

out('-- SAMPLE students for demos and tests. Not real people; card ids are made up.')
out('INSERT INTO student (card_id, name, is_sample) VALUES')
out(
  SAMPLE_NAMES.map((name, i) => `    (${q(`SAMPLE${String(i + 1).padStart(4, '0')}`)}, ${q(name)}, TRUE)`).join(',\n') + ';',
)

writeFileSync(output, lines.join('\n') + '\n')
console.log(`Wrote ${output}`)
console.log(`  floors ${layout.floors.length}, zones ${zoneRows.length}, seats ${layout.totalSeats}, fixtures ${fixtureRows.length}, sample students ${SAMPLE_NAMES.length}`)
